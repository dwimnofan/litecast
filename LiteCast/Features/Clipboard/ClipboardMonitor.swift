import AppKit

/// Polls `NSPasteboard.general.changeCount` on a timer to detect new clipboard contents.
///
/// ## Why polling?
/// macOS provides **no notification API** for pasteboard changes. `NSPasteboard` does not post
/// any `NSNotification`, and there is no `DistributedNotificationCenter` name for it.
/// Apple's own documentation suggests polling `changeCount`; Raycast, Alfred, Maccy, and all
/// other clipboard managers on macOS use the same approach. A 1-second interval is a good balance
/// between responsiveness and CPU cost.
///
/// ## Filtering
/// Skips items that are:
/// - **Concealed** (`org.nspasteboard.ConcealedType`) — set by password managers like 1Password.
/// - **Transient** (`org.nspasteboard.TransientType`) — temporary items not meant for history.
/// - **Auto-generated** (`org.nspasteboard.AutoGeneratedType`) — auto-fill, etc.
/// - **Empty** (no text and no image).
/// - From an **excluded app** (by bundle ID).
/// - Copies made **by LiteCast itself** (tracked via the last changeCount after our writes).
@MainActor
final class ClipboardMonitor {
    /// NSPasteboard type strings per nspasteboard.org conventions.
    static let concealedType = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    private let historyStore: ClipboardHistoryStore
    private let preferences: PreferencesStore
    private var timer: Timer?
    private var lastChangeCount: Int

    /// Set this after LiteCast writes to the pasteboard so we skip our own copies.
    var lastOwnWriteChangeCount: Int = -1

    init(historyStore: ClipboardHistoryStore, preferences: PreferencesStore) {
        self.historyStore = historyStore
        self.preferences = preferences
        self.lastChangeCount = NSPasteboard.general.changeCount
    }

    /// Poll interval. `changeCount` is cheap; 2s is plenty for history UX and keeps idle CPU near zero.
    static let pollInterval: TimeInterval = 2.0

    func start() {
        guard timer == nil else { return }
        lastChangeCount = NSPasteboard.general.changeCount
        let timer = Timer(timeInterval: Self.pollInterval, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated {
                self?.poll()
            }
        }
        // Prefer common modes so we still poll during tracking/scroll; tolerance lets the run loop coalesce.
        timer.tolerance = Self.pollInterval * 0.25
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
        Log.app.info("Clipboard monitor started")
    }

    func stop() {
        timer?.invalidate()
        timer = nil
        Log.app.info("Clipboard monitor stopped")
    }

    var isRunning: Bool { timer != nil }

    // MARK: - Pure filtering logic (testable)

    /// Returns `true` if the given pasteboard types indicate a concealed/transient/auto-generated item.
    static func shouldSkipTypes(_ types: [NSPasteboard.PasteboardType]) -> Bool {
        let typeSet = Set(types)
        return typeSet.contains(concealedType)
            || typeSet.contains(transientType)
            || typeSet.contains(autoGeneratedType)
    }

    /// Prefer image when TIFF/PNG is present; otherwise use string content.
    static func payload(from pasteboard: NSPasteboard) -> ClipboardPayload? {
        if let imageData = pasteboard.data(forType: .tiff) ?? pasteboard.data(forType: .png),
           ClipboardHistoryStore.pngData(fromImageData: imageData) != nil {
            return .image(imageData)
        }
        if let text = pasteboard.string(forType: .string),
           !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            return .text(text)
        }
        return nil
    }

    enum ClipboardPayload {
        case text(String)
        case image(Data)
    }

    // MARK: - Polling

    private func poll() {
        let pb = NSPasteboard.general
        let newCount = pb.changeCount
        guard preferences.clipboardHistoryEnabled else { return }
        guard newCount != lastChangeCount else { return }
        lastChangeCount = newCount

        // Skip copies made by LiteCast itself.
        if newCount == lastOwnWriteChangeCount { return }

        // Check concealed/transient/auto-generated types.
        if let types = pb.types, Self.shouldSkipTypes(types) { return }

        // Check excluded apps.
        let bundleID = NSWorkspace.shared.frontmostApplication?.bundleIdentifier
        if let bundleID, preferences.clipboardExcludedApps.contains(bundleID) { return }

        switch Self.payload(from: pb) {
        case .text(let text):
            historyStore.add(text: text, sourceAppBundleID: bundleID)
        case .image(let data):
            guard let (png, width, height) = ClipboardHistoryStore.pngData(fromImageData: data) else { return }
            historyStore.addImage(pngData: png, width: width, height: height, sourceAppBundleID: bundleID)
        case nil:
            return
        }
    }
}
