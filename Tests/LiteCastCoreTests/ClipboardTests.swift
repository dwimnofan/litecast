import AppKit
import XCTest
@testable import LiteCast

@MainActor
final class ClipboardTests: XCTestCase {

    // MARK: - Helpers

    private func makeStore(directory: URL? = nil) -> ClipboardHistoryStore {
        let dir = directory ?? FileManager.default.temporaryDirectory
            .appendingPathComponent("LiteCastTests-\(UUID().uuidString)", isDirectory: true)
        let store = JSONFileStore<[ClipboardItem]>(filename: "clipboard-history.json", directory: dir)
        return ClipboardHistoryStore(store: store, defaults: UserDefaults(suiteName: "litecast.tests.\(UUID().uuidString)")!)
    }

    private func isolated(_ dir: URL) -> ClipboardHistoryStore {
        ClipboardHistoryStore(store: JSONFileStore(filename: "clipboard-history.json", directory: dir),
                              defaults: UserDefaults(suiteName: "litecast.tests.\(UUID().uuidString)")!)
    }

    // MARK: - Dedupe / Move-to-Top

    func testDeduplicateMovesToTop() {
        let store = makeStore()
        store.add(text: "alpha")
        store.add(text: "beta")
        store.add(text: "gamma")
        XCTAssertEqual(store.items.map(\.text), ["gamma", "beta", "alpha"])

        // Re-copying "alpha" moves it to the top.
        store.add(text: "alpha")
        XCTAssertEqual(store.items.map(\.text), ["alpha", "gamma", "beta"])
        // Count stays the same (no duplicate).
        XCTAssertEqual(store.items.count, 3)
    }

    func testDeduplicateUsesExactMatch() {
        let store = makeStore()
        store.add(text: "hello")
        store.add(text: "Hello")
        // Different case → both kept.
        XCTAssertEqual(store.items.count, 2)
    }

    // MARK: - Retention Pruning by Count

    func testPruneByCountKeepsMaxItems() {
        let store = makeStore()
        store.maxItemCount = 3
        for i in 0..<5 {
            store.add(text: "item \(i)")
        }
        XCTAssertEqual(store.items.count, 3)
        // Most recent items are kept.
        XCTAssertEqual(store.items.map(\.text), ["item 4", "item 3", "item 2"])
    }

    // MARK: - Retention Pruning by Age

    func testPruneByAgeRemovesOldItems() {
        let store = makeStore()
        store.retentionAge = .oneDay

        let now = Date()
        let old = now.addingTimeInterval(-2 * 86400) // 2 days ago
        let recent = now.addingTimeInterval(-3600) // 1 hour ago

        store.add(text: "old", date: old)
        store.add(text: "recent", date: recent)

        // Prune with "now" as the reference.
        store.prune(now: now)
        XCTAssertEqual(store.items.map(\.text), ["recent"])
    }

    func testPruneForeverKeepsAll() {
        let store = makeStore()
        store.retentionAge = .forever

        let veryOld = Date().addingTimeInterval(-365 * 86400) // 1 year ago
        store.add(text: "ancient", date: veryOld)
        store.add(text: "today")
        store.prune()
        XCTAssertEqual(store.items.count, 2)
    }

