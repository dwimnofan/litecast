import XCTest
@testable import LiteCast

@MainActor
final class ClipboardTests: XCTestCase {

    // MARK: - Helpers

    private func makeStore(directory: URL? = nil) -> ClipboardHistoryStore {
        let dir = directory ?? FileManager.default.temporaryDirectory
            .appendingPathComponent("LiteCastTests-\(UUID().uuidString)", isDirectory: true)
        let store = JSONFileStore<[ClipboardItem]>(filename: "clipboard-history.json", directory: dir)
        return ClipboardHistoryStore(store: store, defaults: UserDefaults(suiteName: "litecast.tests.\(UUID().uuidString)")!)
    }

    private func isolated(_ dir: URL) -> ClipboardHistoryStore {
        ClipboardHistoryStore(store: JSONFileStore(filename: "clipboard-history.json", directory: dir),
                              defaults: UserDefaults(suiteName: "litecast.tests.\(UUID().uuidString)")!)
    }

    // MARK: - Dedupe / Move-to-Top

    func testDeduplicateMovesToTop() {
        let store = makeStore()
        store.add(text: "alpha")
        store.add(text: "beta")
        store.add(text: "gamma")
        XCTAssertEqual(store.items.map(\.text), ["gamma", "beta", "alpha"])

        // Re-copying "alpha" moves it to the top.
        store.add(text: "alpha")
        XCTAssertEqual(store.items.map(\.text), ["alpha", "gamma", "beta"])
        // Count stays the same (no duplicate).
        XCTAssertEqual(store.items.count, 3)
    }

    func testDeduplicateUsesExactMatch() {
        let store = makeStore()
        store.add(text: "hello")
        store.add(text: "Hello")
        // Different case → both kept.
        XCTAssertEqual(store.items.count, 2)
    }

    // MARK: - Retention Pruning by Count

    func testPruneByCountKeepsMaxItems() {
        let store = makeStore()
        store.maxItemCount = 3
        for i in 0..<5 {
            store.add(text: "item \(i)")
        }
        XCTAssertEqual(store.items.count, 3)
        // Most recent items are kept.
        XCTAssertEqual(store.items.map(\.text), ["item 4", "item 3", "item 2"])
    }

    // MARK: - Retention Pruning by Age

    func testPruneByAgeRemovesOldItems() {
        let store = makeStore()
        store.retentionAge = .oneDay

        let now = Date()
        let old = now.addingTimeInterval(-2 * 86400) // 2 days ago
        let recent = now.addingTimeInterval(-3600) // 1 hour ago

        store.add(text: "old", date: old)
        store.add(text: "recent", date: recent)

        // Prune with "now" as the reference.
        store.prune(now: now)
        XCTAssertEqual(store.items.map(\.text), ["recent"])
    }

    func testPruneForeverKeepsAll() {
        let store = makeStore()
        store.retentionAge = .forever

        let veryOld = Date().addingTimeInterval(-365 * 86400) // 1 year ago
        store.add(text: "ancient", date: veryOld)
        store.add(text: "today")
        store.prune()
        XCTAssertEqual(store.items.count, 2)
    }

    // MARK: - Concealed-Type Filtering

    func testShouldSkipConcealedTypes() {
        let types: [NSPasteboard.PasteboardType] = [
            .string,
            ClipboardMonitor.concealedType,
        ]
        XCTAssertTrue(ClipboardMonitor.shouldSkipTypes(types))
    }

    func testShouldSkipTransientTypes() {
        let types: [NSPasteboard.PasteboardType] = [
            .string,
            ClipboardMonitor.transientType,
        ]
        XCTAssertTrue(ClipboardMonitor.shouldSkipTypes(types))
    }

    func testShouldSkipAutoGeneratedTypes() {
        let types: [NSPasteboard.PasteboardType] = [
            .string,
            ClipboardMonitor.autoGeneratedType,
        ]
        XCTAssertTrue(ClipboardMonitor.shouldSkipTypes(types))
    }

    func testShouldNotSkipNormalTypes() {
        let types: [NSPasteboard.PasteboardType] = [
            .string,
            .rtf,
        ]
        XCTAssertFalse(ClipboardMonitor.shouldSkipTypes(types))
    }

    func testShouldSkipEmptyTypes() {
        XCTAssertFalse(ClipboardMonitor.shouldSkipTypes([]))
    }

    // MARK: - Provider Prefix Behaviour

    func testProviderReturnsEmptyForEmptyQuery() {
        let store = makeStore()
        store.add(text: "some text")
        let provider = ClipboardHistoryProvider(historyStore: store)
        XCTAssertTrue(provider.results(for: "").isEmpty)
        XCTAssertTrue(provider.results(for: "   ").isEmpty)
    }

    func testProviderPrefixClipReturnsResults() {
        let store = makeStore()
        store.add(text: "invoice from Apple")
        store.add(text: "receipt from Google")
        let provider = ClipboardHistoryProvider(historyStore: store)

        let results = provider.results(for: "clip invoice")
        XCTAssertFalse(results.isEmpty)
        XCTAssertTrue(results.allSatisfy { $0.accessory == "Clipboard" })
        // Should match the invoice item
        XCTAssertTrue(results.contains { $0.title.contains("invoice") })
    }

    func testProviderPrefixCbReturnsResults() {
        let store = makeStore()
        store.add(text: "some important note")
        let provider = ClipboardHistoryProvider(historyStore: store)

        let results = provider.results(for: "cb note")
        XCTAssertFalse(results.isEmpty)
    }

    func testProviderCapsAtFiveWithoutPrefix() {
        let store = makeStore()
        for i in 0..<20 {
            store.add(text: "text item number \(i)")
        }
        let provider = ClipboardHistoryProvider(historyStore: store)

        let results = provider.results(for: "text")
        XCTAssertLessThanOrEqual(results.count, 5)
    }

    func testProviderAllowsUpToFiftyWithPrefix() {
        let store = makeStore()
        for i in 0..<60 {
            store.add(text: "text item number \(i)")
        }
        let provider = ClipboardHistoryProvider(historyStore: store)

        let results = provider.results(for: "clip text")
        XCTAssertLessThanOrEqual(results.count, 50)
        XCTAssertGreaterThan(results.count, 5)
    }

    func testProviderActionIsCopyText() {
        let store = makeStore()
        store.add(text: "hello world")
        let provider = ClipboardHistoryProvider(historyStore: store)

        let results = provider.results(for: "clip hello")
        XCTAssertEqual(results.first?.action, .copyText("hello world"))
    }

    func testProviderBarePrefixListsNewestAndPlainEmptyIsEmpty() {
        let store = makeStore()
        store.add(text: "first")
        store.add(text: "second")
        let provider = ClipboardHistoryProvider(historyStore: store)
        XCTAssertEqual(provider.results(for: "clip ").map(\.title), ["second", "first"])
        XCTAssertEqual(provider.results(for: "CB ").count, 2)
        XCTAssertTrue(provider.results(for: "clip").isEmpty || provider.results(for: "clip").count <= 5)
    }

    func testProviderScoresBelowAppsWithoutPrefix() {
        let store = makeStore()
        store.add(text: "safari bookmark")
        let provider = ClipboardHistoryProvider(historyStore: store)
        let plain = provider.results(for: "safari")
        XCTAssertEqual(plain.count, 1)
        XCTAssertLessThan(plain[0].score, 400)
        XCTAssertGreaterThan(provider.results(for: "clip safari")[0].score, plain[0].score)
    }

    func testRetentionSettingsPersistAndPruneOnChange() {
        let dir = FileManager.default.temporaryDirectory.appendingPathComponent("LiteCastTests-\(UUID().uuidString)")
        defer { try? FileManager.default.removeItem(at: dir) }
        let defaults = UserDefaults(suiteName: "litecast.tests.\(UUID().uuidString)")!
        let file = JSONFileStore<[ClipboardItem]>(filename: "clipboard-history.json", directory: dir)
        let store = ClipboardHistoryStore(store: file, defaults: defaults)
        for i in 0..<5 { store.add(text: "n\(i)") }
        store.maxItemCount = 2
        XCTAssertEqual(store.items.count, 2)
        store.retentionAge = .thirtyDays
        let again = ClipboardHistoryStore(store: file, defaults: defaults)
        XCTAssertEqual(again.maxItemCount, 2)
        XCTAssertEqual(again.retentionAge, .thirtyDays)
        XCTAssertEqual(again.items.count, 2)
    }

    // MARK: - Store Round-Trip with Temp Directory

    func testStoreRoundTrip() throws {
        let dir = FileManager.default.temporaryDirectory
            .appendingPathComponent("LiteCastTests-\(UUID().uuidString)", isDirectory: true)
        defer { try? FileManager.default.removeItem(at: dir) }

        // Write
        let store1 = isolated(dir)
        store1.add(text: "persisted text", sourceAppBundleID: "com.apple.Safari")
        store1.add(text: "another item")
        XCTAssertEqual(store1.items.count, 2)

        // Read back
        let store2 = isolated(dir)
        XCTAssertEqual(store2.items.count, 2)
        XCTAssertEqual(store2.items[0].text, "another item")
        XCTAssertEqual(store2.items[1].text, "persisted text")
        XCTAssertEqual(store2.items[1].sourceAppBundleID, "com.apple.Safari")
    }

    func testCorruptFileStartsEmptyWithoutOverwriting() throws {
        let dir = FileManager.default.temporaryDirectory
            .appendingPathComponent("LiteCastTests-\(UUID().uuidString)", isDirectory: true)
        try FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        defer { try? FileManager.default.removeItem(at: dir) }

        // Write corrupt data.
        let filePath = dir.appendingPathComponent("clipboard-history.json")
        try Data("not json!!".utf8).write(to: filePath)

        let store = isolated(dir)
        // Should start empty.
        XCTAssertTrue(store.items.isEmpty)

        // The corrupt file should NOT have been overwritten.
        let raw = try String(contentsOf: filePath, encoding: .utf8)
        XCTAssertEqual(raw, "not json!!")

        // First write moves the corrupt file aside rather than destroying it.
        store.add(text: "fresh")
        let backup = try String(contentsOf: filePath.appendingPathExtension("corrupt"), encoding: .utf8)
        XCTAssertEqual(backup, "not json!!")
    }

    // MARK: - ClearAll

    func testClearAllRemovesEverything() {
        let store = makeStore()
        store.add(text: "one")
        store.add(text: "two")
        XCTAssertEqual(store.items.count, 2)
        store.clearAll()
        XCTAssertTrue(store.items.isEmpty)
    }

    // MARK: - ClipboardItem

    func testClipboardItemCodable() throws {
        let item = ClipboardItem(text: "test", sourceAppBundleID: "com.apple.Notes")
        let data = try JSONEncoder().encode(item)
        let decoded = try JSONDecoder().decode(ClipboardItem.self, from: data)
        XCTAssertEqual(decoded.text, item.text)
        XCTAssertEqual(decoded.id, item.id)
        XCTAssertEqual(decoded.sourceAppBundleID, item.sourceAppBundleID)
    }

    // MARK: - Preferences Defaults

    func testClipboardHistoryDefaultsToOff() throws {
        let suite = "com.dwimnofan.litecast.tests.clipboard.\(UUID().uuidString)"
        let defaults = try XCTUnwrap(UserDefaults(suiteName: suite))
        defer { UserDefaults().removePersistentDomain(forName: suite) }

        let store = PreferencesStore(defaults: defaults)
        XCTAssertFalse(store.clipboardHistoryEnabled)
    }

    func testClipboardHistoryEnabledPersists() throws {
        let suite = "com.dwimnofan.litecast.tests.clipboard.\(UUID().uuidString)"
        let defaults = try XCTUnwrap(UserDefaults(suiteName: suite))
        defer { UserDefaults().removePersistentDomain(forName: suite) }

        let store = PreferencesStore(defaults: defaults)
        store.clipboardHistoryEnabled = true
        let store2 = PreferencesStore(defaults: defaults)
        XCTAssertTrue(store2.clipboardHistoryEnabled)
    }

    func testClipboardExcludedAppsPersist() throws {
        let suite = "com.dwimnofan.litecast.tests.clipboard.\(UUID().uuidString)"
        let defaults = try XCTUnwrap(UserDefaults(suiteName: suite))
        defer { UserDefaults().removePersistentDomain(forName: suite) }

        let store = PreferencesStore(defaults: defaults)
        store.clipboardExcludedApps = ["com.app.one", "com.app.two"]
        let store2 = PreferencesStore(defaults: defaults)
        XCTAssertEqual(store2.clipboardExcludedApps, ["com.app.one", "com.app.two"])
    }
}
